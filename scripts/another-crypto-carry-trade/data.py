"""Builds assets/js/another-crypto-carry-trade/data.js for the post's d3 charts.

Sources:
  - binance: weekly 30-day average BTCUSDT funding, annualized (%), copied from the
    2factor landing page's cost chart (frg-web twofactor_index.html, `DATA.funding_pct`).
  - jrcost: the same chart's estimated Jr cost (`DATA.senior_pct`, Sr yield / 3), weekly (%).
  - deribit: BTC-PERPETUAL funding from Deribit's public API, weekly mean, annualized (%).
  - usde: Ethena USDe circulating supply from DefiLlama's stablecoins API (id 146), weekly.
  - month: daily.json in this folder (2factor analytics DB, base-cbbtc strategies view).
  - susde: sUSDe staking yield (%) from DefiLlama's yields API, weekly mean on the usde weeks.
  - btc: weekly BTC-PERPETUAL closes from Deribit's public chart API, the last three years ($k).

    python3 scripts/another-crypto-carry-trade/data.py <path to twofactor_index.html>
"""

import json
import os
import sys
import time
import urllib.request
from datetime import date, datetime, timedelta, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "assets", "js", "another-crypto-carry-trade", "data.js")


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    return json.load(urllib.request.urlopen(req, timeout=60))


def binance(site_html):
    line = next(l for l in open(site_html) if "var DATA = {" in l and "funding_pct" in l)
    d = json.loads(line[line.index("{"):line.rindex("}") + 1])
    return ([[t, round(v, 2)] for t, v in zip(d["dates"], d["funding_pct"])],
            [[t, round(v, 2)] for t, v in zip(d["dates"], d["senior_pct"])])


def deribit(weeks):
    start = int(datetime.fromisoformat(weeks[0]).replace(tzinfo=timezone.utc).timestamp() * 1000)
    end = int(time.time() * 1000)
    hourly, t = {}, start
    while t < end:
        e = min(t + 30 * 86400000, end)
        r = get("https://www.deribit.com/api/v2/public/get_funding_rate_history"
                f"?instrument_name=BTC-PERPETUAL&start_timestamp={t}&end_timestamp={e}")
        for x in r["result"]:
            hourly[x["timestamp"]] = x["interest_1h"]
        t = e
        time.sleep(0.1)
    # Weekly buckets keyed by the Monday-free week start used by the Binance series (Thursdays).
    out, d0 = {}, date.fromisoformat(weeks[0])
    for ts, v in hourly.items():
        day = datetime.fromtimestamp(ts / 1000, timezone.utc).date()
        wk = d0 + timedelta(days=7 * ((day - d0).days // 7))
        out.setdefault(wk.isoformat(), []).append(v)
    return [[k, round(sum(v) / len(v) * 24 * 365 * 100, 2)] for k, v in sorted(out.items()) if len(v) > 100]


def usde():
    r = get("https://stablecoins.llama.fi/stablecoin/146")
    pts = r["tokens"] if "tokens" in r else []
    weekly = {}
    for p in pts:
        day = datetime.fromtimestamp(int(p["date"]), timezone.utc).date()
        if day.weekday() == 3:  # Thursdays, to line up with the funding series
            weekly[day.isoformat()] = round(p["circulating"]["peggedUSD"] / 1e9, 3)
    return sorted([k, v] for k, v in weekly.items())


def susde(weeks):
    r = get("https://yields.llama.fi/chart/66985a81-9c51-46ca-9977-42b4fe7bc6df")["data"]
    pts = [(p["timestamp"][:10], p["apy"]) for p in r if p.get("apy") is not None]
    out = []
    for w in weeks:
        lo = (date.fromisoformat(w) - timedelta(days=7)).isoformat()
        v = [a for t, a in pts if lo < t <= w]
        if v:
            out.append([w, round(sum(v) / len(v), 2)])
    return out


def btc():
    end = int(time.time() * 1000)
    start = end - 3 * 365 * 86400000
    r = get("https://www.deribit.com/api/v2/public/get_tradingview_chart_data"
            f"?instrument_name=BTC-PERPETUAL&start_timestamp={start}&end_timestamp={end}&resolution=1D")["result"]
    daily = [[datetime.fromtimestamp(t / 1000, timezone.utc).date().isoformat(), round(c / 1000, 3)]
             for t, c in zip(r["ticks"], r["close"])]
    return daily[::7] + ([daily[-1]] if (len(daily) - 1) % 7 else [])


def month():
    rows = json.load(open(os.path.join(HERE, "daily.json")))
    return [{"t": r["t"], "veranta": round(100 * r["ver"], 3), "hyperliquid": round(100 * r["hl"], 3),
             "jr": round(-100 * r["jr"], 3), "sr": round(100 * r["sr"], 3),
             "L": round(r["L"], 5)} for r in rows]


def main():
    b, jrcost = binance(sys.argv[1])
    u = usde()
    data = {"binance": b, "deribit": deribit([w for w, _ in b]), "jrcost": jrcost, "usde": u, "susde": susde([w for w, _ in u]), "month": month(), "btc": btc()}
    with open(OUT, "w") as fh:
        fh.write("// Generated by scripts/another-crypto-carry-trade/data.py. Do not edit by hand.\n")
        fh.write("window.JPC_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print({k: (len(v), v[0], v[-1]) for k, v in data.items()})


if __name__ == "__main__":
    main()
